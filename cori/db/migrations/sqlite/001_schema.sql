-- SQLite mirror of oracle/001_schema.sql (dev/test fallback only).
-- Money is stored as TEXT so values round-trip exactly as Decimal.
-- Dates are ISO-8601 TEXT. Embeddings are JSON arrays; VECTOR_DISTANCE is a
-- Python function registered on the connection.

CREATE TABLE CURRENCIES (
  CURRENCY_CODE TEXT PRIMARY KEY, NAME TEXT NOT NULL, MINOR_UNITS INTEGER NOT NULL, SYMBOL TEXT);

CREATE TABLE FX_RATES (
  RATE_DATE TEXT NOT NULL, FROM_CURRENCY TEXT NOT NULL REFERENCES CURRENCIES, TO_CURRENCY TEXT NOT NULL REFERENCES CURRENCIES,
  RATE TEXT NOT NULL, PRIMARY KEY (FROM_CURRENCY, TO_CURRENCY, RATE_DATE));

CREATE TABLE VENDORS (
  VENDOR_ID TEXT PRIMARY KEY, NAME TEXT NOT NULL, COUNTRY TEXT NOT NULL,
  DEFAULT_CURRENCY TEXT NOT NULL REFERENCES CURRENCIES, STATUS TEXT NOT NULL DEFAULT 'ACTIVE');

CREATE TABLE VENDOR_CURRENCIES (
  VENDOR_ID TEXT NOT NULL REFERENCES VENDORS, CURRENCY_CODE TEXT NOT NULL REFERENCES CURRENCIES,
  PRIMARY KEY (VENDOR_ID, CURRENCY_CODE));

CREATE TABLE VENDOR_BANK_ACCOUNTS (
  ACCOUNT_ID INTEGER PRIMARY KEY, VENDOR_ID TEXT NOT NULL REFERENCES VENDORS, BANK_NAME TEXT NOT NULL,
  IBAN_OR_ACCOUNT TEXT NOT NULL, SWIFT_BIC TEXT, IS_ACTIVE INTEGER NOT NULL DEFAULT 1);

CREATE TABLE CLIENTS (CLIENT_ID INTEGER PRIMARY KEY, CLIENT_NUMBER TEXT NOT NULL UNIQUE, NAME TEXT NOT NULL);

CREATE TABLE MATTERS (
  MATTER_ID INTEGER PRIMARY KEY, CLIENT_ID INTEGER NOT NULL REFERENCES CLIENTS, MATTER_NUMBER TEXT NOT NULL UNIQUE,
  DESCRIPTION TEXT, STATUS TEXT NOT NULL DEFAULT 'OPEN');

CREATE TABLE INVOICES (
  INVOICE_ID INTEGER PRIMARY KEY, VENDOR_ID TEXT REFERENCES VENDORS, MATTER_ID INTEGER REFERENCES MATTERS,
  INVOICE_NUMBER TEXT, INVOICE_DATE TEXT, CURRENCY TEXT, SUBTOTAL TEXT, TAX TEXT, TOTAL TEXT, TOTAL_USD TEXT,
  STATUS TEXT NOT NULL, SOURCE TEXT NOT NULL DEFAULT 'HISTORICAL', FILE_PATH TEXT, ORIGINAL_FILENAME TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IX_INVOICES_VENDOR_NUM ON INVOICES (VENDOR_ID, INVOICE_NUMBER);
CREATE INDEX IX_INVOICES_MATTER ON INVOICES (MATTER_ID, INVOICE_DATE);
CREATE INDEX IX_INVOICES_STATUS ON INVOICES (STATUS);

CREATE TABLE INVOICE_LINE_ITEMS (
  LINE_ID INTEGER PRIMARY KEY, INVOICE_ID INTEGER NOT NULL REFERENCES INVOICES, DESCRIPTION TEXT, TIMEKEEPER TEXT,
  QUANTITY TEXT, UNIT_PRICE TEXT, AMOUNT TEXT);
CREATE INDEX IX_LINE_ITEMS_INVOICE ON INVOICE_LINE_ITEMS (INVOICE_ID);

CREATE TABLE INVOICE_EMBEDDINGS (
  INVOICE_ID INTEGER PRIMARY KEY REFERENCES INVOICES, EMBEDDING TEXT NOT NULL, MODEL_NAME TEXT,
  CREATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE AGENT_BATCHES (
  BATCH_ID TEXT PRIMARY KEY, SUBMITTED_BY TEXT NOT NULL, SUBMITTED_AT TEXT NOT NULL, STATUS TEXT NOT NULL,
  INVOICE_COUNT INTEGER NOT NULL, FINISHED_AT TEXT);

CREATE TABLE AGENT_BATCH_ITEMS (
  BATCH_ID TEXT NOT NULL REFERENCES AGENT_BATCHES, INVOICE_ID INTEGER NOT NULL, STATUS TEXT NOT NULL,
  CURRENT_STEP TEXT, UPDATED_AT TEXT NOT NULL, PRIMARY KEY (BATCH_ID, INVOICE_ID));

CREATE TABLE AGENT_RUNS (
  RUN_ID TEXT PRIMARY KEY, BATCH_ID TEXT, INVOICE_ID INTEGER, AGENT_NAME TEXT NOT NULL, MODEL_NAME TEXT,
  PROMPT_VERSION TEXT, RAW_OUTPUT TEXT, STARTED_AT TEXT NOT NULL, FINISHED_AT TEXT, STATUS TEXT NOT NULL,
  ERROR_MESSAGE TEXT);
CREATE INDEX IX_AGENT_RUNS_INVOICE ON AGENT_RUNS (INVOICE_ID, BATCH_ID);

CREATE TABLE AGENT_DECISIONS (
  DECISION_ID TEXT PRIMARY KEY, INVOICE_ID INTEGER NOT NULL, BATCH_ID TEXT NOT NULL, DECISION TEXT NOT NULL,
  SUMMARY TEXT, REASONS TEXT, CONSENSUS TEXT, FLAGS TEXT, DETAIL TEXT, FX_RATE_USED TEXT, FX_RATE_DATE TEXT,
  DECIDED_AT TEXT NOT NULL);
CREATE INDEX IX_AGENT_DECISIONS_INVOICE ON AGENT_DECISIONS (INVOICE_ID, DECIDED_AT);

CREATE TABLE REVIEW_FEEDBACK (
  FEEDBACK_ID TEXT PRIMARY KEY, INVOICE_ID INTEGER NOT NULL, FIELD_NAME TEXT NOT NULL, AGENT_VALUE TEXT,
  CORRECTED_VALUE TEXT, REVIEWER TEXT NOT NULL, REVIEWED_AT TEXT NOT NULL, FLAG_CLEARED TEXT);

CREATE TABLE AGENT_INVOICE_EXTRACTS (
  INVOICE_ID INTEGER PRIMARY KEY, BATCH_ID TEXT NOT NULL, VENDOR_ID TEXT, MATTER_ID INTEGER, INVOICE_NUMBER TEXT,
  INVOICE_DATE TEXT, CURRENCY TEXT, TOTAL TEXT, TOTAL_USD TEXT, DECISION TEXT, UPDATED_AT TEXT NOT NULL);
CREATE INDEX IX_AGENT_EXTRACTS_VENDOR ON AGENT_INVOICE_EXTRACTS (VENDOR_ID, INVOICE_NUMBER);
