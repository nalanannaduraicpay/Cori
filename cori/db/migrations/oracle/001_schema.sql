-- Cori mock IAS schema for Oracle AI Database 26ai (also runs on 23ai Free).
-- Run as the schema owner (ORACLE_ADMIN_USER). Statements are separated by a
-- line containing only "/" (parsed by scripts/migrate.py).
-- Uses only features common to 23ai and 26ai: VECTOR type, IS JSON checks.

CREATE TABLE CURRENCIES (
  CURRENCY_CODE  VARCHAR2(3)   PRIMARY KEY,
  NAME           VARCHAR2(100) NOT NULL,
  MINOR_UNITS    NUMBER(1)     NOT NULL,
  SYMBOL         VARCHAR2(10)
)
/
CREATE TABLE FX_RATES (
  RATE_DATE      DATE          NOT NULL,
  FROM_CURRENCY  VARCHAR2(3)   NOT NULL REFERENCES CURRENCIES (CURRENCY_CODE),
  TO_CURRENCY    VARCHAR2(3)   NOT NULL REFERENCES CURRENCIES (CURRENCY_CODE),
  RATE           NUMBER(24,12) NOT NULL,
  CONSTRAINT PK_FX_RATES PRIMARY KEY (FROM_CURRENCY, TO_CURRENCY, RATE_DATE)
)
/
CREATE TABLE VENDORS (
  VENDOR_ID         VARCHAR2(20)  PRIMARY KEY,
  NAME              VARCHAR2(200) NOT NULL,
  COUNTRY           VARCHAR2(2)   NOT NULL,
  DEFAULT_CURRENCY  VARCHAR2(3)   NOT NULL REFERENCES CURRENCIES (CURRENCY_CODE),
  STATUS            VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL
)
/
CREATE TABLE VENDOR_CURRENCIES (
  VENDOR_ID      VARCHAR2(20) NOT NULL REFERENCES VENDORS (VENDOR_ID),
  CURRENCY_CODE  VARCHAR2(3)  NOT NULL REFERENCES CURRENCIES (CURRENCY_CODE),
  CONSTRAINT PK_VENDOR_CURRENCIES PRIMARY KEY (VENDOR_ID, CURRENCY_CODE)
)
/
CREATE TABLE VENDOR_BANK_ACCOUNTS (
  ACCOUNT_ID       NUMBER        PRIMARY KEY,
  VENDOR_ID        VARCHAR2(20)  NOT NULL REFERENCES VENDORS (VENDOR_ID),
  BANK_NAME        VARCHAR2(200) NOT NULL,
  IBAN_OR_ACCOUNT  VARCHAR2(50)  NOT NULL,
  SWIFT_BIC        VARCHAR2(11),
  IS_ACTIVE        NUMBER(1)     DEFAULT 1 NOT NULL
)
/
CREATE TABLE CLIENTS (
  CLIENT_ID      NUMBER        PRIMARY KEY,
  CLIENT_NUMBER  VARCHAR2(20)  NOT NULL UNIQUE,
  NAME           VARCHAR2(200) NOT NULL
)
/
CREATE TABLE MATTERS (
  MATTER_ID      NUMBER        PRIMARY KEY,
  CLIENT_ID      NUMBER        NOT NULL REFERENCES CLIENTS (CLIENT_ID),
  MATTER_NUMBER  VARCHAR2(20)  NOT NULL UNIQUE,
  DESCRIPTION    VARCHAR2(400),
  STATUS         VARCHAR2(20)  DEFAULT 'OPEN' NOT NULL
)
/
CREATE TABLE INVOICES (
  INVOICE_ID         NUMBER        PRIMARY KEY,
  VENDOR_ID          VARCHAR2(20)  REFERENCES VENDORS (VENDOR_ID),
  MATTER_ID          NUMBER        REFERENCES MATTERS (MATTER_ID),
  INVOICE_NUMBER     VARCHAR2(60),
  INVOICE_DATE       DATE,
  CURRENCY           VARCHAR2(3),
  SUBTOTAL           NUMBER(18,4),
  TAX                NUMBER(18,4),
  TOTAL              NUMBER(18,4),
  TOTAL_USD          NUMBER(18,4),
  STATUS             VARCHAR2(30)  NOT NULL,
  SOURCE             VARCHAR2(20)  DEFAULT 'HISTORICAL' NOT NULL,
  FILE_PATH          VARCHAR2(500),
  ORIGINAL_FILENAME  VARCHAR2(260),
  CREATED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX IX_INVOICES_VENDOR_NUM ON INVOICES (VENDOR_ID, INVOICE_NUMBER)
/
CREATE INDEX IX_INVOICES_MATTER ON INVOICES (MATTER_ID, INVOICE_DATE)
/
CREATE INDEX IX_INVOICES_STATUS ON INVOICES (STATUS)
/
CREATE TABLE INVOICE_LINE_ITEMS (
  LINE_ID      NUMBER        PRIMARY KEY,
  INVOICE_ID   NUMBER        NOT NULL REFERENCES INVOICES (INVOICE_ID),
  DESCRIPTION  VARCHAR2(500),
  TIMEKEEPER   VARCHAR2(100),
  QUANTITY     NUMBER(12,4),
  UNIT_PRICE   NUMBER(18,4),
  AMOUNT       NUMBER(18,4)
)
/
CREATE INDEX IX_LINE_ITEMS_INVOICE ON INVOICE_LINE_ITEMS (INVOICE_ID)
/
CREATE TABLE INVOICE_EMBEDDINGS (
  INVOICE_ID  NUMBER        PRIMARY KEY REFERENCES INVOICES (INVOICE_ID),
  EMBEDDING   VECTOR(*, FLOAT32) NOT NULL,
  MODEL_NAME  VARCHAR2(100),
  CREATED_AT  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE AGENT_BATCHES (
  BATCH_ID       VARCHAR2(36)  PRIMARY KEY,
  SUBMITTED_BY   VARCHAR2(100) NOT NULL,
  SUBMITTED_AT   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  STATUS         VARCHAR2(20)  NOT NULL,
  INVOICE_COUNT  NUMBER        NOT NULL,
  FINISHED_AT    TIMESTAMP
)
/
CREATE TABLE AGENT_BATCH_ITEMS (
  BATCH_ID      VARCHAR2(36) NOT NULL REFERENCES AGENT_BATCHES (BATCH_ID),
  INVOICE_ID    NUMBER       NOT NULL,
  STATUS        VARCHAR2(30) NOT NULL,
  CURRENT_STEP  VARCHAR2(40),
  UPDATED_AT    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_AGENT_BATCH_ITEMS PRIMARY KEY (BATCH_ID, INVOICE_ID)
)
/
CREATE TABLE AGENT_RUNS (
  RUN_ID          VARCHAR2(36)  PRIMARY KEY,
  BATCH_ID        VARCHAR2(36),
  INVOICE_ID      NUMBER,
  AGENT_NAME      VARCHAR2(60)  NOT NULL,
  MODEL_NAME      VARCHAR2(120),
  PROMPT_VERSION  VARCHAR2(60),
  RAW_OUTPUT      CLOB CHECK (RAW_OUTPUT IS JSON),
  STARTED_AT      TIMESTAMP     NOT NULL,
  FINISHED_AT     TIMESTAMP,
  STATUS          VARCHAR2(20)  NOT NULL,
  ERROR_MESSAGE   VARCHAR2(4000)
)
/
CREATE INDEX IX_AGENT_RUNS_INVOICE ON AGENT_RUNS (INVOICE_ID, BATCH_ID)
/
CREATE TABLE AGENT_DECISIONS (
  DECISION_ID   VARCHAR2(36)  PRIMARY KEY,
  INVOICE_ID    NUMBER        NOT NULL,
  BATCH_ID      VARCHAR2(36)  NOT NULL,
  DECISION      VARCHAR2(30)  NOT NULL,
  SUMMARY       CLOB,
  REASONS       CLOB CHECK (REASONS IS JSON),
  CONSENSUS     CLOB CHECK (CONSENSUS IS JSON),
  FLAGS         CLOB CHECK (FLAGS IS JSON),
  DETAIL        CLOB CHECK (DETAIL IS JSON),
  FX_RATE_USED  NUMBER(24,12),
  FX_RATE_DATE  DATE,
  DECIDED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX IX_AGENT_DECISIONS_INVOICE ON AGENT_DECISIONS (INVOICE_ID, DECIDED_AT)
/
CREATE TABLE REVIEW_FEEDBACK (
  FEEDBACK_ID      VARCHAR2(36)   PRIMARY KEY,
  INVOICE_ID       NUMBER         NOT NULL,
  FIELD_NAME       VARCHAR2(100)  NOT NULL,
  AGENT_VALUE      VARCHAR2(4000),
  CORRECTED_VALUE  VARCHAR2(4000),
  REVIEWER         VARCHAR2(100)  NOT NULL,
  REVIEWED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  FLAG_CLEARED     VARCHAR2(60)
)
/
-- Header fields Cori agreed on for each uploaded invoice it processed. Lets the
-- duplicate check see earlier submissions without giving the agent user write
-- access to INVOICES. One row per invoice (latest run wins).
CREATE TABLE AGENT_INVOICE_EXTRACTS (
  INVOICE_ID      NUMBER        PRIMARY KEY,
  BATCH_ID        VARCHAR2(36)  NOT NULL,
  VENDOR_ID       VARCHAR2(20),
  MATTER_ID       NUMBER,
  INVOICE_NUMBER  VARCHAR2(60),
  INVOICE_DATE    DATE,
  CURRENCY        VARCHAR2(3),
  TOTAL           NUMBER(18,4),
  TOTAL_USD       NUMBER(18,4),
  DECISION        VARCHAR2(30),
  UPDATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX IX_AGENT_EXTRACTS_VENDOR ON AGENT_INVOICE_EXTRACTS (VENDOR_ID, INVOICE_NUMBER)
/
